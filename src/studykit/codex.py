"""`studykit codex agents [--check]`: the Codex custom agents (docs/architecture.md §5.5).

Codex reads project subagents from `.codex/agents/*.toml` (`name`, `description`,
`developer_instructions`, optional `model_reasoning_effort`). They are generated from the
Claude Code agents in `.claude/agents/*.md`, so both runtimes share one text: the TOML
holds the agent's description, its effort, a short Codex preamble (the skills it must read
first, since Codex cannot preload them, and the tools it may use) and the agent's body
verbatim. `--check` fails when a file is missing, stale or left over.

Only the worker agents that the commands start become Codex agents; the tutor and the
examiner run as the main thread (`just tutor`, `just examine`) and need none.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from studykit import tools

CODEX_AGENTS = ("ingester", "exam-analyst", "author", "verifier")
HEADER = "# Generated by `studykit codex agents` from .claude/agents/{name}.md; do not edit.\n"

# what a Claude Code tool list allows, said for Codex
WRITE_TOOLS = {"Write", "Edit"}


def claude_agent(path: Path) -> tuple[dict, str]:
    """(frontmatter, body) of a Claude Code agent file."""
    text = path.read_text("utf-8")
    end = text.index("\n---\n", 4)
    return yaml.safe_load(text[4:end]), text[end + 5 :].strip("\n")


def _toml_string(text: str) -> str:
    if "'''" not in text:
        return "'''\n" + text + "\n'''"  # a literal string keeps backslashes as written
    return json.dumps(text, ensure_ascii=False)


def preamble(name: str, meta: dict) -> str:
    skills = meta.get("skills") or []
    tool_list = [t.strip() for t in str(meta.get("tools", "")).split(",") if t.strip()]
    lines = [
        f"You run as a Codex subagent of study-kit. The instructions below are the `{name}` "
        f"agent of `.claude/agents/{name}.md`, written for Claude Code; AGENTS.md (section "
        '"Codex") maps their tool names to yours.',
        "",
    ]
    if skills:
        lines.append(
            "Before anything else, read these skills in full (Codex does not preload them): "
            + ", ".join(f"`.claude/skills/{s}/SKILL.md`" for s in skills)
            + "."
        )
    if WRITE_TOOLS.isdisjoint(tool_list):
        writes = "never change a file except through the `studykit` commands below"
    else:
        writes = "write only the files the instructions below name"
    lines.append(f"Claude Code gives this agent only {', '.join(tool_list)}: {writes}.")
    if name == "verifier":
        lines.append(
            "Codex has no hook that keeps you blind, so you keep yourself blind: never read, "
            "list, search or print anything under a course's `exercises/`, `mc/`, `exams/`, "
            "`state/`, `_history/` or `_build/` (only `_build/blind/` and figure images), nor "
            "`site/dist`, `.cache/` or `*.facts.json`, and never run `studykit verify` with "
            "`--json` or `--show-key`, `studykit render` or `studykit pdf`."
        )
    return "\n".join(lines)


def render(name: str, path: Path) -> str:
    meta, body = claude_agent(path)
    out = [HEADER.format(name=name)]
    out.append(f"name = {json.dumps(name)}")
    out.append(f"description = {json.dumps(meta['description'], ensure_ascii=False)}")
    if meta.get("effort"):
        out.append(f"model_reasoning_effort = {json.dumps(meta['effort'])}")
    instructions = preamble(name, meta) + "\n\n" + body
    out.append(f"developer_instructions = {_toml_string(instructions)}")
    return "\n".join(out) + "\n"


def expected(root: Path | None = None) -> dict[Path, str]:
    root = root or tools.repo_root()
    src = root / ".claude" / "agents"
    dst = root / ".codex" / "agents"
    return {dst / f"{name}.toml": render(name, src / f"{name}.md") for name in CODEX_AGENTS}


def sync(check: bool, root: Path | None = None) -> list[str]:
    """Write (or, with `check`, compare) the agent files; returns the problems or changes."""
    root = root or tools.repo_root()
    want = expected(root)
    dst = root / ".codex" / "agents"
    messages: list[str] = []
    for path, text in want.items():
        rel = path.relative_to(root).as_posix()
        have = path.read_text("utf-8") if path.is_file() else None
        if have == text:
            continue
        messages.append(f"{rel}: {'missing' if have is None else 'stale'}")
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, "utf-8")
    for path in sorted(dst.glob("*.toml")) if dst.is_dir() else []:
        if path not in want:
            messages.append(f"{path.relative_to(root).as_posix()}: not generated")
            if not check:
                path.unlink()
    return messages
